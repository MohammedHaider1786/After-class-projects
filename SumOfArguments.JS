// Function to calculate sum of arguments
function sumOfArguments(a, b, c) {
    let sum = a + b + c;
    console.log("Sum of arguments:", sum);
}

// Call the function
sumOfArguments(10, 20, 30);

// Trigonometric values (degrees converted to radians)
let degree = 30;
let radian = degree * (Math.PI / 180);

console.log("Sin 30°:", Math.sin(radian));
console.log("Cos 30°:", Math.cos(radian));
console.log("Tan 30°:", Math.tan(radian));
